"""Aggregate grid results into mean +/- std tables, paired GCN-BERT gaps, and figures.

Usage: python scripts/aggregate.py --results-dir results/main

Writes to <results-dir>/: summary.md, summary.csv, tables.tex,
figures/data_efficiency.png, figures/confusion_full_data.png
"""
import argparse
import json
from collections import defaultdict
from pathlib import Path

import numpy as np
import pandas as pd

BERT_COLOR, GCN_COLOR = '#2a78d6', '#eb6834'
INK, INK_MUTED, GRID = '#0b0b0b', '#52514e', '#e4e3df'
LABELS = ['negative', 'neutral', 'positive']


def load_runs(results_dir):
    rows, confusions = [], defaultdict(lambda: np.zeros((3, 3), dtype=int))
    for path in sorted(Path(results_dir).glob('*_fraction*_seed*.json')):
        r = json.loads(path.read_text())
        model = path.name.split('_')[0]
        for eval_domain, m in r.get('test', {}).items():
            rows.append({
                'model': model, 'train_domain': r['domain'], 'eval_domain': eval_domain,
                'setting': m['setting'], 'fraction': r['train_fraction'], 'seed': r['seed'],
                'train_size': r['train_size'], 'n_evaluated': m['n_evaluated'],
                'accuracy': 100 * m['test_accuracy'], 'macro_f1': 100 * m['test_macro_f1'],
                'val_macro_f1': 100 * r['validation_metrics']['eval_macro_f1'],
            })
            confusions[(model, r['domain'], eval_domain, r['train_fraction'])] += np.array(m['confusion_matrix'])
    return pd.DataFrame(rows), confusions


def pm(mean, std, n):
    return f'{mean:.2f} ± {std:.2f}' if n > 1 else f'{mean:.2f} (n=1)'


def summarise(df):
    keys = ['train_domain', 'eval_domain', 'fraction', 'model']
    g = df.groupby(keys).agg(acc_mean=('accuracy', 'mean'), acc_std=('accuracy', 'std'),
                             f1_mean=('macro_f1', 'mean'), f1_std=('macro_f1', 'std'),
                             n_seeds=('seed', 'nunique'), train_size=('train_size', 'first'),
                             n_eval=('n_evaluated', 'first')).reset_index()
    return g.fillna(0.0)


def paired_gaps(df):
    """GCN minus BERT, paired by (train domain, eval domain, fraction, seed)."""
    keys = ['train_domain', 'eval_domain', 'fraction', 'seed']
    wide = df.pivot_table(index=keys, columns='model', values=['accuracy', 'macro_f1']).dropna()
    if wide.empty or ('accuracy', 'gcn') not in wide.columns or ('accuracy', 'bert') not in wide.columns:
        return pd.DataFrame()
    diff = pd.DataFrame({
        'd_acc': wide[('accuracy', 'gcn')] - wide[('accuracy', 'bert')],
        'd_f1': wide[('macro_f1', 'gcn')] - wide[('macro_f1', 'bert')],
    }).reset_index()
    return diff.groupby(['train_domain', 'eval_domain', 'fraction']).agg(
        d_acc_mean=('d_acc', 'mean'), d_acc_std=('d_acc', 'std'),
        d_f1_mean=('d_f1', 'mean'), d_f1_std=('d_f1', 'std'),
        gcn_wins_f1=('d_f1', lambda x: int((x > 0).sum())), n_pairs=('d_f1', 'size'),
    ).reset_index().fillna(0.0)


def write_markdown(summary, gaps, out):
    lines = ['# Results summary', '',
             'All numbers are test-set percentages, mean ± std over seeds. '
             'Checkpoints were selected on validation macro-F1 only.', '']
    for (train, evald), block in summary.groupby(['train_domain', 'eval_domain']):
        setting = 'in-domain' if train == evald else 'cross-domain'
        lines += [f'## Train {train} → test {evald} ({setting})', '',
                  '| Fraction | Train size | Model | Accuracy | Macro-F1 | Seeds |', '|---|---|---|---|---|---|']
        for _, r in block.sort_values(['fraction', 'model'], ascending=[False, True]).iterrows():
            lines.append(f"| {r.fraction:g} | {r.train_size} | {r.model.upper()} | "
                         f"{pm(r.acc_mean, r.acc_std, r.n_seeds)} | {pm(r.f1_mean, r.f1_std, r.n_seeds)} | {r.n_seeds} |")
        lines.append('')
    if not gaps.empty:
        lines += ['## Paired gap: GCN − BERT (percentage points)', '',
                  '| Train → Test | Fraction | Δ Accuracy | Δ Macro-F1 | GCN wins (F1) |', '|---|---|---|---|---|']
        for _, r in gaps.sort_values(['train_domain', 'eval_domain', 'fraction']).iterrows():
            lines.append(f"| {r.train_domain} → {r.eval_domain} | {r.fraction:g} | "
                         f"{r.d_acc_mean:+.2f} ± {r.d_acc_std:.2f} | {r.d_f1_mean:+.2f} ± {r.d_f1_std:.2f} | "
                         f"{r.gcn_wins_f1}/{r.n_pairs} |")
    out.write_text('\n'.join(lines) + '\n', encoding='utf-8')


def write_latex(summary, gaps, out):
    def cell(m, s, n):
        return f'${m:.2f} \\pm {s:.2f}$' if n > 1 else f'${m:.2f}$'
    tex = ['% Generated by scripts/aggregate.py -- do not edit by hand.',
           '% Main table: full training data.',
           '\\begin{tabular}{llcc}', '\\toprule',
           'Train $\\rightarrow$ Test & Model & Accuracy & Macro-F1 \\\\', '\\midrule']
    full = summary[summary.fraction == 1.0]
    for (train, evald), block in full.groupby(['train_domain', 'eval_domain']):
        for _, r in block.sort_values('model').iterrows():
            tex.append(f"{train.capitalize()} $\\rightarrow$ {evald.capitalize()} & "
                       f"{'BERT+GCN' if r.model == 'gcn' else 'BERT'} & "
                       f"{cell(r.acc_mean, r.acc_std, r.n_seeds)} & {cell(r.f1_mean, r.f1_std, r.n_seeds)} \\\\")
    tex += ['\\bottomrule', '\\end{tabular}', '']
    if not gaps.empty:
        tex += ['% Paired GCN - BERT gap in macro-F1 (pp) by label fraction.',
                '\\begin{tabular}{l' + 'c' * gaps.fraction.nunique() + '}', '\\toprule',
                'Train $\\rightarrow$ Test & ' + ' & '.join(f'{f:g}' for f in sorted(gaps.fraction.unique())) + ' \\\\',
                '\\midrule']
        for (train, evald), block in gaps.groupby(['train_domain', 'eval_domain']):
            cells = [f'${r.d_f1_mean:+.2f} \\pm {r.d_f1_std:.2f}$' for _, r in block.sort_values('fraction').iterrows()]
            tex.append(f"{train.capitalize()} $\\rightarrow$ {evald.capitalize()} & " + ' & '.join(cells) + ' \\\\')
        tex += ['\\bottomrule', '\\end{tabular}']
    out.write_text('\n'.join(tex) + '\n', encoding='utf-8')


def style_axis(ax):
    for side in ('top', 'right'):
        ax.spines[side].set_visible(False)
    for side in ('left', 'bottom'):
        ax.spines[side].set_color(GRID)
    ax.tick_params(colors=INK_MUTED, labelsize=8, length=0)
    ax.grid(axis='y', color=GRID, linewidth=0.8)
    ax.set_axisbelow(True)


def plot_data_efficiency(summary, out):
    import matplotlib
    matplotlib.use('Agg')
    import matplotlib.pyplot as plt
    import matplotlib.ticker
    pairs = [(t, e) for t in ('restaurant', 'laptop') for e in ('restaurant', 'laptop')]
    fig, axes = plt.subplots(1, 4, figsize=(12, 3.1), sharey=True)
    for ax, (train, evald) in zip(axes, pairs):
        block = summary[(summary.train_domain == train) & (summary.eval_domain == evald)]
        style_axis(ax)
        for model, color, name in (('bert', BERT_COLOR, 'BERT'), ('gcn', GCN_COLOR, 'BERT+GCN')):
            b = block[block.model == model].sort_values('fraction')
            if b.empty:
                continue
            x = b.fraction * 100
            ax.fill_between(x, b.f1_mean - b.f1_std, b.f1_mean + b.f1_std, color=color, alpha=0.15, linewidth=0)
            ax.plot(x, b.f1_mean, color=color, linewidth=2, marker='o', markersize=5, label=name)
        tag = 'in-domain' if train == evald else 'cross-domain'
        ax.set_title(f'{train.capitalize()} → {evald.capitalize()} ({tag})', fontsize=9, color=INK)
        ax.set_xscale('log')
        ax.xaxis.set_minor_locator(matplotlib.ticker.NullLocator())
        ax.set_xticks([10, 25, 50, 100])
        ax.set_xticklabels(['10%', '25%', '50%', '100%'])
        ax.set_xlabel('Training labels used', fontsize=8, color=INK_MUTED)
    axes[0].set_ylabel('Test macro-F1 (%)', fontsize=8, color=INK_MUTED)
    handles, labels = axes[0].get_legend_handles_labels()
    fig.legend(handles, labels, loc='upper center', ncol=2, frameon=False, fontsize=9,
               bbox_to_anchor=(0.5, 1.04))
    fig.tight_layout(rect=(0, 0, 1, 0.93))
    fig.savefig(out, dpi=200, bbox_inches='tight')
    plt.close(fig)


def plot_confusions(confusions, out):
    import matplotlib
    matplotlib.use('Agg')
    import matplotlib.pyplot as plt
    import matplotlib.ticker
    panels = [(m, d) for d in ('restaurant', 'laptop') for m in ('bert', 'gcn')
              if (m, d, d, 1.0) in confusions]
    if not panels:
        return
    fig, axes = plt.subplots(1, len(panels), figsize=(3.1 * len(panels), 3.0))
    axes = np.atleast_1d(axes)
    for ax, (model, domain) in zip(axes, panels):
        cm = confusions[(model, domain, domain, 1.0)]
        norm = cm / cm.sum(axis=1, keepdims=True).clip(min=1)
        ax.imshow(norm, cmap='Blues', vmin=0, vmax=1)
        for i in range(3):
            for j in range(3):
                ax.text(j, i, f'{100 * norm[i, j]:.0f}%', ha='center', va='center', fontsize=8,
                        color='white' if norm[i, j] > 0.55 else INK)
        ax.set_xticks(range(3)); ax.set_yticks(range(3))
        ax.set_xticklabels(['neg', 'neu', 'pos'], fontsize=8, color=INK_MUTED)
        ax.set_yticklabels(['neg', 'neu', 'pos'], fontsize=8, color=INK_MUTED)
        ax.set_xlabel('Predicted', fontsize=8, color=INK_MUTED)
        ax.set_ylabel('Gold', fontsize=8, color=INK_MUTED)
        ax.set_title(f"{'BERT+GCN' if model == 'gcn' else 'BERT'} — {domain.capitalize()}", fontsize=9, color=INK)
        for spine in ax.spines.values():
            spine.set_visible(False)
        ax.tick_params(length=0)
    fig.tight_layout()
    fig.savefig(out, dpi=200, bbox_inches='tight')
    plt.close(fig)


def main():
    p = argparse.ArgumentParser()
    p.add_argument('--results-dir', default='results/main')
    args = p.parse_args()
    root = Path(args.results_dir)
    df, confusions = load_runs(root)
    if df.empty:
        raise SystemExit(f'No finished runs in {root}')
    summary, gaps = summarise(df), paired_gaps(df)
    df.to_csv(root / 'runs.csv', index=False)
    summary.to_csv(root / 'summary.csv', index=False)
    write_markdown(summary, gaps, root / 'summary.md')
    write_latex(summary, gaps, root / 'tables.tex')
    (root / 'figures').mkdir(exist_ok=True)
    plot_data_efficiency(summary, root / 'figures' / 'data_efficiency.png')
    plot_confusions(confusions, root / 'figures' / 'confusion_full_data.png')
    print((root / 'summary.md').read_text())


if __name__ == '__main__':
    main()

"""Regenerate results/INDEX.md from the files that actually exist."""
from pathlib import Path

ROOTS = ('baseline', 'low_resource', 'custom', 'ablation', 'epoch_sweep', 'cross_domain', 'predictions')
REPORTS = [
    ('Original model comparison runs', 'reports/all_metrics.csv'),
    ('Completed/pending run matrix', 'reports/experiment_status.csv'),
    ('Grouped means and sample SD', 'reports/summary_by_group.csv'),
    ('Full-data comparison', 'reports/baseline_summary.csv'),
    ('Data-budget comparison', 'reports/low_resource_summary.csv'),
    ('Cross-domain comparison', 'reports/cross_domain_summary.csv'),
    ('Graph control (dependency vs identity)', 'reports/ablation_summary.csv'),
    ('Extension comparisons', 'reports/extension_summary.md'),
    ('Extension comparisons (CSV)', 'reports/extension_summary.csv'),
    ('Rule-based error analysis', 'error_analysis.md'),
]


def main():
    lines = ['# Experiment results', '',
             'Generated by `scripts/write_index.py`. Paths are relative to this file.', '']
    lines += ['## Reports', '']
    for name, path in REPORTS:
        exists = (Path('results') / path).is_file()
        lines.append(f"- [{name}]({path})" + ('' if exists else ' *(not generated yet)*'))
    lines += ['', 'Mean and sample standard deviation are computed over the seeds present in each group.',
              'A single-seed group has no standard deviation.', '', '## Saved experiment records', '']
    for root in ROOTS:
        files = sorted(Path('results', root).rglob('*.json*'))
        if not files:
            continue
        lines.append(f'### {root} ({len(files)} files)')
        lines.append('')
        for path in files[:400]:
            rel = path.relative_to('results')
            lines.append(f'- [{rel}]({rel})')
        lines.append('')
    Path('results/INDEX.md').write_text('\n'.join(lines).rstrip() + '\n', encoding='utf-8')
    print('Wrote results/INDEX.md')


if __name__ == '__main__':
    main()

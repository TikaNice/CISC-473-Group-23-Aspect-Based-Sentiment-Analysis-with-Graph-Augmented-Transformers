"""Refresh the numbers block in README.md from the current result summaries."""
import csv
from pathlib import Path

START = '<!-- RESULTS:START -->'
END = '<!-- RESULTS:END -->'
README = Path('README.md')


def read_rows(path):
    path = Path(path)
    if not path.is_file():
        return []
    with path.open(newline='', encoding='utf-8') as f:
        return list(csv.DictReader(f))


def pct(value):
    return f'{100 * float(value):.2f}'


def main():
    if not README.is_file():
        print('README.md not found')
        return
    text = README.read_text(encoding='utf-8')
    if START not in text or END not in text:
        print('README.md has no RESULTS block; leaving it unchanged')
        return
    base = read_rows('results/reports/baseline_summary.csv')
    low = read_rows('results/reports/low_resource_summary.csv')
    cross = read_rows('results/reports/cross_domain_summary.csv')
    abl = read_rows('results/reports/ablation_summary.csv')

    lines = ['', '| Setting | BERT macro-F1 | BERT+GCN macro-F1 |', '|---|---:|---:|']
    for domain in ('restaurant', 'laptop'):
        recs = {r['model']: r for r in base if r['domain'] == domain and float(r['fraction']) == 1}
        if len(recs) == 2:
            lines.append(f"| {domain.capitalize()}, full data | "
                         f"{pct(recs['bert']['test_macro_f1_mean'])} ± {pct(recs['bert']['test_macro_f1_std'])} | "
                         f"{pct(recs['gcn']['test_macro_f1_mean'])} ± {pct(recs['gcn']['test_macro_f1_std'])} |")
    recs = {r['model']: r for r in cross}
    if len(recs) == 2:
        lines.append(f"| Restaurant → Laptop (zero-shot) | "
                     f"{pct(recs['bert']['test_macro_f1_mean'])} ± {pct(recs['bert']['test_macro_f1_std'])} | "
                     f"{pct(recs['gcn']['test_macro_f1_mean'])} ± {pct(recs['gcn']['test_macro_f1_std'])} |")

    if low:
        lines += ['', '| Domain | Budget | BERT | BERT+GCN | Paired Δ |', '|---|---:|---:|---:|---:|']
        for domain in ('restaurant', 'laptop'):
            for frac in (0.1, 0.25, 0.5, 1.0):
                recs = {r['model']: r for r in low if r['domain'] == domain and float(r['fraction']) == frac}
                if len(recs) < 2 or any(r['seeds'] != '42,43,44' for r in recs.values()):
                    continue
                b = 100 * float(recs['bert']['test_f1_mean'])
                g = 100 * float(recs['gcn']['test_f1_mean'])
                lines.append(f'| {domain.capitalize()} | {int(round(frac*100))}% | {b:.2f} | {g:.2f} | {g-b:+.2f} |')

    if abl:
        lines += ['', '| Domain | Budget | Dependency | Identity (self-loops) | Paired Δ |', '|---|---:|---:|---:|---:|']
        for domain in ('restaurant', 'laptop'):
            for frac in (0.1, 1.0):
                dep = [r for r in abl if r['domain'] == domain and float(r['fraction']) == frac and r['graph'] == 'dependency']
                ident = [r for r in abl if r['domain'] == domain and float(r['fraction']) == frac and r['graph'] == 'identity']
                if not dep or not ident or not dep[0]['paired_sd']:
                    continue
                d, i = dep[0], ident[0]
                delta = 100 * float(d['paired_dependency_minus_identity_mean'])
                lines.append(f"| {domain.capitalize()} | {int(round(frac*100))}% | "
                             f"{pct(d['test_macro_f1_mean'])} | {pct(i['test_macro_f1_mean'])} | {delta:+.2f} |")
    lines += ['', 'The first table gives mean ± sample SD. The budget and graph-control tables give means. '
                  'Paired deltas compare GCN minus BERT for budgets and dependency minus identity for graph control. '
                  'All numbers are regenerated by `bash scripts/reproduce.sh`.']

    block = START + '\n' + '\n'.join(lines) + '\n' + END
    before, _, after = text.partition(START)
    _, _, tail = after.partition(END)
    updated = before + block + tail
    if updated != text:
        README.write_text(updated, encoding='utf-8')
        print('README.md results block refreshed')


if __name__ == '__main__':
    main()
